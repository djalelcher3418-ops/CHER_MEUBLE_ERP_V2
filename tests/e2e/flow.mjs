const problems = []
async function newPage() {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, serviceWorkers: 'block', acceptDownloads: true })
  await ctx.route('https://fonts.googleapis.com/**', (r) => r.abort())
  const p = await ctx.newPage()
  p.on('dialog', (d) => d.accept())
  p.on('pageerror', (e) => problems.push('pageerror: ' + e.message))
  p.on('response', async (r) => {
    const u = r.url()
    if (r.status() >= 400 && !(u.includes('manage-users') && r.request().postData()?.includes('ping')) && /\/(rest|functions|auth|storage)\/v1\//.test(u)) problems.push(`${r.status()} ${r.request().method()} ${decodeURIComponent(u.replace('http://localhost:4174', ''))} :: ${(await r.text().catch(() => '')).slice(0, 200)}`)
  })
  return p
}
